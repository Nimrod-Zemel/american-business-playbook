#!/usr/bin/env python3
"""The guide is the source. Check that the rule tables still say what it says.

    python3 tools/guide.py            exit 1 when the reading copy is stale or a line is missing
    python3 tools/guide.py --write    regenerate the Markdown reading copy from the Word file
    python3 tools/guide.py --lines    every English line the guide quotes, and the table that holds it

docs/guide/ holds "The American Playbook", the guide this skill encodes, as
the Word file its authors wrote. Two things are derived from that file and
checked on every build:

  1. A Markdown reading copy, so the guide can be read on GitHub. It is
     generated, never edited by hand.
  2. A list of every English line the guide puts in a founder's mouth or in an
     American's: quoted lines, and the lines of its templates. Each must exist
     in the rule tables under skills/<skill>/data/. A line the guide has and
     the tables lack is a rule the engine does not know.

When a new version of the guide arrives: replace the Word file, update the
version and the hash in data/coach.json, run this tool, and add whatever it
reports as missing.

Standard library only. The Word file is read as a zip of XML and nothing in it
is executed.
"""

import argparse
import hashlib
import json
import os
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

import _paths

GUIDE_DIR = os.path.join(_paths.REPO, "docs", "guide")
DOCX = "The-American-Playbook-V2.docx"
COPY = "the-american-playbook-v2.md"
W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
HEBREW = re.compile(r"[֐-׿]")
QUOTED = re.compile(r'"([^"\n]{6,400})"')

# Quoted in the guide, and not a line anyone says: names of things.
NOT_LINES = {
    "Americanize My Email": "the name of the prompt; the prompt itself is in templates.json",
    "The American Meeting": "the name of a workshop the guide suggests to program managers",
}

HEADER = (
    "<!-- GENERATED by tools/guide.py from %s. Do not edit by hand: replace the Word file, "
    "then run `python3 tools/guide.py --write`. -->\n"
)
PREFACE = """# The American Playbook, {version}

The guide this skill is built on, by {authors}. Last updated {updated}.

This page is a reading copy, generated from the Word file next to it ([`{docx}`]({docx})), which is the original. The guide is written in Hebrew, with its scripts and templates in English. What the guide is to the skill, and the terms it is shared under, are in the [README](README.md) of this folder.
"""


# ------------------------------------------------------------------ reading

def _on(properties, tag):
    node = properties.find(W + tag) if properties is not None else None
    return node is not None and node.get(W + "val") not in ("0", "false")


def _runs(paragraph):
    """(text, bold) for every run of a paragraph, adjacent runs of the same weight merged."""
    out = []
    for run in paragraph.iter(W + "r"):
        properties = run.find(W + "rPr")
        bold = _on(properties, "b") or _on(properties, "bCs")
        text = ""
        for node in run:
            if node.tag == W + "t":
                text += node.text or ""
            elif node.tag == W + "br":
                text += "\n"
            elif node.tag == W + "tab":
                text += " "
        if not text:
            continue
        if out and out[-1][1] == bold:
            out[-1] = (out[-1][0] + text, bold)
        else:
            out.append((text, bold))
    return out


def _plain(paragraph):
    return "".join(text for text, _bold in _runs(paragraph)).strip()


def _kind(paragraph):
    properties = paragraph.find(W + "pPr")
    if properties is None:
        return "text"
    style = properties.find(W + "pStyle")
    if style is not None and style.get(W + "val") in ("Heading1", "Heading2"):
        return "h2" if style.get(W + "val") == "Heading1" else "h3"
    return "item" if properties.find(W + "numPr") is not None else "text"


def read(path=None):
    """The guide as a list of blocks: paragraphs, and tables as rows of cells of paragraphs."""
    path = path or os.path.join(GUIDE_DIR, DOCX)
    with zipfile.ZipFile(path) as archive:
        root = ET.fromstring(archive.read("word/document.xml"))
    blocks = []
    for node in root.find(W + "body"):
        if node.tag == W + "p":
            blocks.append({"kind": _kind(node), "runs": _runs(node), "text": _plain(node)})
        elif node.tag == W + "tbl":
            rows = []
            for row in node.findall(W + "tr"):
                rows.append([
                    [{"runs": _runs(p), "text": _plain(p)} for p in cell.findall(W + "p")]
                    for cell in row.findall(W + "tc")
                ])
            blocks.append({"kind": "table", "rows": rows})
    return blocks


def sha256(path=None):
    with open(path or os.path.join(GUIDE_DIR, DOCX), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def words(blocks):
    """Every word of the guide, in order: what the reading copy must also say."""
    out = []
    for block in blocks:
        if block["kind"] == "table":
            for row in block["rows"]:
                for cell in row:
                    for paragraph in cell:
                        out.extend(paragraph["text"].split())
        else:
            out.extend(block["text"].split())
    return out


# ---------------------------------------------------------------- rendering

def _escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*", "\\*").replace("_", "\\_")


def _inline(runs, cell=False):
    parts = []
    for text, bold in runs:
        shown = _escape(text).replace("\n", "<br>")
        if cell:
            shown = shown.replace("|", "\\|")
        lead = shown[: len(shown) - len(shown.lstrip())]
        tail = shown[len(shown.rstrip()):]
        core = shown.strip()
        parts.append("%s<b>%s</b>%s" % (lead, core, tail) if bold and core else shown)
    return "".join(parts).strip()


def _is_english(text):
    return bool(text) and not HEBREW.search(text)


def _english_box(cell):
    """A one-cell box that holds scripts or a template: mostly English lines to copy."""
    filled = [p for p in cell if p["text"]]
    english = [p for p in filled if _is_english(p["text"])]
    return len(english) >= 2 and len(english) * 2 >= len(filled)


def render(blocks, meta):
    """The Markdown reading copy. Hebrew sits in right-to-left blocks, English boxes stay left-to-right."""
    out, rtl = [], []

    def flush():
        if rtl:
            out.append('<div dir="rtl">\n\n%s\n\n</div>' % "\n\n".join(rtl))
            del rtl[:]

    for block in blocks:
        kind = block["kind"]
        if kind in ("h2", "h3"):
            rtl.append("%s %s" % ("##" if kind == "h2" else "###", _escape(block["text"])))
        elif kind == "item":
            line = "- %s" % _inline(block["runs"])
            if rtl and rtl[-1].startswith("- "):
                rtl[-1] += "\n" + line
            else:
                rtl.append(line)
        elif kind == "text":
            if block["text"]:
                rtl.append(_inline(block["runs"]))
        else:
            rows = block["rows"]
            if len(rows) == 1 and len(rows[0]) == 1:
                cell = rows[0][0]
                if _english_box(cell):
                    lines, started = [], False
                    for paragraph in cell:
                        if not started and paragraph["text"] and not _is_english(paragraph["text"]):
                            rtl.append("<b>%s</b>" % _escape(paragraph["text"]))
                            continue
                        started = True
                        lines.append(paragraph["text"])
                    while lines and not lines[0]:
                        lines.pop(0)
                    while lines and not lines[-1]:
                        lines.pop()
                    flush()
                    out.append("```text\n%s\n```" % "\n".join(lines))
                else:
                    rtl.append("\n>\n".join("> %s" % _inline(p["runs"]) for p in cell if p["text"]))
            else:
                width = max(len(row) for row in rows)
                table = []
                for index, row in enumerate(rows):
                    cells = ["<br>".join(_inline(p["runs"], cell=True) for p in cell if p["text"]) for cell in row]
                    cells += [""] * (width - len(cells))
                    table.append("| %s |" % " | ".join(cells))
                    if index == 0:
                        table.append("|%s" % (" --- |" * width))
                rtl.append("\n".join(table))
    flush()
    preface = PREFACE.format(docx=DOCX, **meta)
    return HEADER % DOCX + preface + "\n" + "\n\n".join(out) + "\n"


# -------------------------------------------------------------------- lines

def norm(text):
    text = text.lower().replace("’", "'").replace("‘", "'")
    text = re.sub(r"[^a-z0-9' ]+", " ", text).replace("'", "")
    return re.sub(r"\s+", " ", text).strip()


def lines(blocks):
    """Every English line the guide gives: (line, kind), kind being 'quoted' or 'template'."""
    found, seen = [], set()

    def add(line, kind):
        line = line.strip()
        key = norm(line)
        if key and key not in seen:
            seen.add(key)
            found.append((line, kind))

    def quoted(text):
        for span in QUOTED.findall(text.replace("“", '"').replace("”", '"')):
            letters = sum(1 for char in span if char.isascii() and char.isalpha())
            if letters >= 8 and not HEBREW.search(span) and len(span.split()) >= 2:
                add(span, "quoted")

    for block in blocks:
        if block["kind"] != "table":
            quoted(block["text"])
            continue
        rows = block["rows"]
        box = len(rows) == 1 and len(rows[0]) == 1 and _english_box(rows[0][0])
        for row in rows:
            for cell in row:
                for paragraph in cell:
                    text = paragraph["text"]
                    quoted(text)
                    # A template line: English, a sentence and not a label, and not already a quoted script.
                    if box and _is_english(text) and not text.endswith(":") and '"' not in text:
                        for sentence in _sentences(text):
                            add(sentence, "template")
    return found


GREETING = re.compile(r"^(?:Hi|Hello|Dear) [A-Z][\w\[\] ]{0,30}?(?:,| -)\s*")
LABEL = re.compile(r"^(?:Subject:|\d\)|-)\s*")


def _sentences(paragraph):
    """The sentences of a template paragraph that carry wording: four words or more, without the
    greeting or the Subject label. The tables keep a template with named slots, so a line that
    names Michael is looked up from its second sentence on."""
    text = GREETING.sub("", LABEL.sub("", paragraph.strip()))
    return [part.strip() for part in re.split(r"(?<=[.!?])\s+", text) if len(part.split()) >= 4]


def table_text(skill=None):
    """{table name: every string in it, normalized}."""
    data_dir = os.path.join(skill or _paths.SKILL, "data")
    out = {}

    def walk(node, bucket):
        if isinstance(node, dict):
            for value in node.values():
                walk(value, bucket)
        elif isinstance(node, list):
            for value in node:
                walk(value, bucket)
        elif isinstance(node, str):
            bucket.append(norm(node))

    for name in sorted(os.listdir(data_dir)):
        if name.endswith(".json"):
            with open(os.path.join(data_dir, name), "r", encoding="utf-8") as handle:
                bucket = []
                walk(json.load(handle), bucket)
            out[name] = " | ".join(bucket)
    return out


def coverage(blocks=None, skill=None):
    """Where each of the guide's lines lives in the rule tables."""
    blocks = blocks if blocks is not None else read()
    tables = table_text(skill)
    rows = []
    for line, kind in lines(blocks):
        if line in NOT_LINES:
            rows.append({"line": line, "kind": kind, "tables": [], "status": "name", "why": NOT_LINES[line]})
            continue
        homes = [name for name, text in tables.items() if norm(line) in text]
        rows.append({"line": line, "kind": kind, "tables": homes, "status": "found" if homes else "missing"})
    return rows


# --------------------------------------------------------------------- main

def declared(skill=None):
    """What the rule tables say about the guide they implement."""
    with open(os.path.join(skill or _paths.SKILL, "data", "coach.json"), "r", encoding="utf-8") as handle:
        return json.load(handle)["guide"]


def run(root=None):
    """Every way the guide, its reading copy and the rule tables disagree."""
    guide_dir = os.path.join(root, "docs", "guide") if root else GUIDE_DIR
    skill = os.path.join(root, "skills", _paths.SKILL_NAME) if root else _paths.SKILL
    docx = os.path.join(guide_dir, DOCX)
    problems = []
    if not os.path.isfile(docx):
        return {"problems": ["%s is missing" % DOCX], "lines": 0, "found": 0, "names": 0}
    meta = declared(skill)
    if meta["sha256"] != sha256(docx):
        problems.append(
            "the Word file changed (sha256 %s...) and data/coach.json still names %s. "
            "Compare the new guide with the tables, then update the version and the hash" % (sha256(docx)[:12], meta["version"])
        )
    blocks = read(docx)
    try:
        with open(os.path.join(guide_dir, COPY), "r", encoding="utf-8") as handle:
            current = handle.read().replace("\r\n", "\n")
    except OSError:
        current = None
    if current != render(blocks, meta):
        problems.append("%s is stale. Run: python3 tools/guide.py --write" % COPY)
    rows = coverage(blocks, skill)
    for row in rows:
        if row["status"] == "missing":
            problems.append('the guide says "%s" and no rule table has it' % row["line"])
    return {
        "problems": problems,
        "lines": len(rows),
        "found": sum(1 for row in rows if row["status"] == "found"),
        "names": sum(1 for row in rows if row["status"] == "name"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the Markdown reading copy")
    group.add_argument("--lines", action="store_true", help="list the guide's English lines and where each lives")
    args = parser.parse_args()
    if args.write:
        text = render(read(), declared())
        with open(os.path.join(GUIDE_DIR, COPY), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("wrote docs/guide/%s (%d lines)" % (COPY, text.count("\n")))
        return 0
    if args.lines:
        for row in coverage():
            where = ", ".join(row["tables"]) if row["tables"] else row.get("why", "MISSING")
            print("%-8s %-9s %s\n         -> %s" % (row["status"], row["kind"], row["line"], where))
        return 0
    report = run()
    for item in report["problems"]:
        print("GAP: %s" % item)
    if report["problems"]:
        print("The guide and the engine disagree.")
        return 1
    print("Guide OK: %d English lines, %d in the rule tables, %d are names. The reading copy is current." % (
        report["lines"], report["found"], report["names"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
