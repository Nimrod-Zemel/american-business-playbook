LONG_REFERENCE = 300


def with_contents(text):
    """A long reference opens with the list of its sections, so a reader who stops early knows what is below."""
    lines = text.split("\n")
    sections = [index for index, line in enumerate(lines) if line.startswith("## ")]
    if len(lines) <= LONG_REFERENCE or len(sections) < 3:
        return text
    names = [lines[index][3:].strip().strip("`") for index in sections]
    return "\n".join(lines[:sections[0]] + ["In this file: %s." % " | ".join(names), ""] + lines[sections[0]:])


def build():
    references = os.path.join("skills", _paths.SKILL_NAME, "references")
    out = []
    for rel, builder in TARGETS:
        text = builder().rstrip("\n")
        if rel.startswith(references):
            text = with_contents(text)
        out.append((rel, HEADER + text + "\n"))
    for rel, lang in INPLACE:
        path = os.path.join(_paths.REPO, rel)
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as handle:
                out.append((rel, fill_demos(handle.read().replace("\r\n", "\n"), lang)))
    return out


def stale():
    """Relative paths of generated files that differ from what the data would produce."""
    out = []
    for rel, text in build():
        path = os.path.join(_paths.REPO, rel)
        try:
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read().replace("\r\n", "\n")
        except OSError:
            current = None
        if current != text:
            out.append(rel.replace(os.sep, "/"))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if anything is stale")
    args = parser.parse_args()
    if args.check:
        outdated = stale()
        for rel in outdated:
            print("stale: %s" % rel)
        print("Generated files are up to date." if not outdated else "Run: python3 tools/build_refs.py")
        return 1 if outdated else 0
    for rel, text in build():
        path = os.path.join(_paths.REPO, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("wrote %s (%d lines)" % (rel.replace(os.sep, "/"), text.count("\n")))
    return 0


