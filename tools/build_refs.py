def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell).replace("|", "/").replace("\n", " ") for cell in row) + " |")
    return "\n".join(out)


def code(text):
    return "```text\n%s\n```" % text.rstrip("\n")


def strip_ask(text):
    return text[5:] if text.startswith("Ask: ") else text


