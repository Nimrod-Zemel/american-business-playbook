DEMO_BLOCK = re.compile(r"(<!-- demo:([a-z-]+)(?::(en|he))?(:output)? -->\n).*?(<!-- /demo -->)", re.DOTALL)
STAMP_IN_PROSE = re.compile(r"\| rules [0-9a-f]{12} \|")


def fill_demos(text, lang):
    """Refresh the engine output between `<!-- demo:NAME -->` and `<!-- /demo -->` markers.

    A marker may name its own coaching language, `<!-- demo:NAME:he -->`, so one
    page can show the engine speaking English and Hebrew, and may end in
    `:output` to show what the engine printed without the command that asked
    for it. Stamp lines quoted in the prose get the current rules fingerprint,
    so an example never shows a fingerprint the engine no longer prints.
    """
    steps = {}

    def replace(match):
        name, own = match.group(2), match.group(3) or lang
        if own not in steps:
            steps[own] = example_steps(own)
        if name not in steps[own]:
            raise SystemExit("Unknown demo %r. Known: %s" % (name, ", ".join(sorted(steps[own]))))
        step = steps[own][name]
        block = "```text\n%s\n```" % step[1] if match.group(4) else _console(step)
        return "%s%s\n%s" % (match.group(1), block, match.group(5))

    filled = DEMO_BLOCK.sub(replace, text) if "<!-- demo:" in text else text
    return STAMP_IN_PROSE.sub("| rules %s |" % seal.rules_digest(_paths.SKILL), filled)


