def commands():
    parser = cli._parser()
    sub = [action for action in parser._actions if isinstance(action, argparse._SubParsersAction)][0]
    parts = [
        "# Command Reference",
        "",
        "Every command of `scripts/playbook.py`, rendered from the engine's own argument parser and fact-sheet schemas. Common flags on every command: `--format brief|json` (default brief), `--lang he|en` (default he), `--unsealed`.",
        "",
        "Exit codes: 0 ok, 1 the draft or talk track needs work, 2 bad input, 3 the integrity seal is broken.",
        "",
    ]
    for name, summary in cli.COMMANDS:
        parts.extend(["## %s" % name, "", summary, ""])
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            sub.choices[name].print_usage()
        usage = " ".join(buffer.getvalue().replace("usage: ", "").split())
        usage = usage.replace(" [--format {brief,json}] [--lang {he,en}] [--unsealed]", "")
        parts.extend([code(usage), ""])
        if name in cli.FACT_COMMANDS:
            spec, example = cli.FACT_COMMANDS[name]
            parts.extend(["Fact sheet fields (unknown fields are rejected):", "", code("\n".join(cli.describe(spec))), ""])
            if name == "decode":
                lines = []
                for context in decode.CONTEXTS:
                    ids = decode.signal_ids(context)
                    for light in ("green", "yellow", "red"):
                        if ids[light]:
                            lines.append("%s/%s: %s" % (context, light, ", ".join(ids[light])))
                parts.extend(["Signal ids (each needs evidence to count):", "", code("\n".join(lines)), ""])
            parts.extend(["Example:", "", "```json\n%s\n```" % json.dumps(example, ensure_ascii=False, indent=2), ""])
        if name == "lint":
            parts.extend(["Types: %s." % ", ".join("`%s`" % item for item in mail.types()), ""])
        if name == "template":
            parts.extend(["Templates: %s." % ", ".join("`%s`" % item for item in mail.template_ids()), ""])
        if name == "send-time":
            parts.extend(["Zones: %s, any IANA name for those zones, or a major US city." % ", ".join(sorted(clock.zones())), ""])
    return "\n".join(parts)


